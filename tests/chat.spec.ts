  const smallPanel = await panel.boundingBox();
  const smallArea = await area.boundingBox();
  expect(smallPanel!.x).toBeGreaterThanOrEqual(smallArea!.x + 12);
  expect(smallPanel!.y).toBeGreaterThanOrEqual(smallArea!.y + 12);
  expect(smallPanel!.x + smallPanel!.width).toBeLessThanOrEqual(smallArea!.x + smallArea!.width - 12);
  expect(smallPanel!.y + smallPanel!.height).toBeLessThanOrEqual(smallArea!.y + smallArea!.height - 12);
  await expect(page.getByRole("textbox", { name: "채팅 메시지 입력" })).toBeVisible();
  await expect(page.getByRole("dialog", { name: "채팅", exact: true }).getByRole("button", { name: "채팅 닫기", exact: true })).toBeVisible();
